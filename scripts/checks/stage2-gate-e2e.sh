#!/usr/bin/env bash
# End-to-end evidence for the required-mode security gate (W8 Stage 2).
#
# Runs the real `sop security scan` against a temporary repository and temporary
# Stage 2 configuration, so the gate is exercised as an operator would meet it.
# It never reads or writes the repository's own config, baseline, or OSV database.
#
# Required on PATH: gitleaks, semgrep, osv-scanner (the pinned builds; the CI job
# prepends the provisioned tools directory). cargo-audit is intentionally absent:
# OSV-Scanner covers the Rust lockfile here, and the cargo-audit pin matrix has its
# own repository test.
#
# Environment:
#   SOP_SECURITY_E2E_RULES   Semgrep rules directory (default: .agent-sdlc/security-rules)
#   SOP_SECURITY_E2E_SOP     Pre-built sop binary (default: built into a temp dir)
#
# Cases, each asserting the exact verdict of `sop security scan --json`:
#   valid database                     -> PASS
#   missing database                   -> INDETERMINATE
#   stale database (> 90 days)         -> INDETERMINATE
#   corrupt database (digest mismatch) -> INDETERMINATE
#   missing required language coverage -> INDETERMINATE
#   unpinned scanner binary            -> INDETERMINATE
#   new unsuppressed HIGH finding      -> FAIL

set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
rules="${SOP_SECURITY_E2E_RULES:-$root/.agent-sdlc/security-rules}"

die() { echo "stage2-gate-e2e: $*" >&2; exit 1; }

for cmd in gitleaks semgrep osv-scanner python3; do
  command -v "$cmd" >/dev/null 2>&1 || die "$cmd is required on PATH"
done
[ -d "$rules" ] || die "semgrep rules directory not found: $rules"

work="$(mktemp -d "${TMPDIR:-/tmp}/sop-stage2-e2e.XXXXXX")"
if [ "${SOP_SECURITY_E2E_KEEP:-0}" = "1" ]; then
  echo "stage2-gate-e2e: keeping $work" >&2
else
  trap 'rm -rf "$work"' EXIT
fi

sop_bin="${SOP_SECURITY_E2E_SOP:-}"
if [ -z "$sop_bin" ]; then
  sop_bin="$work/sop"
  ( cd "$root" && go build -o "$sop_bin" ./cmd/sop ) || die "sop build failed"
fi

repo="$work/repo"
mkdir -p "$repo"
# A hand-written Cargo.lock gives the dependency scanner real lockfile content
# without network access, so the database freshness and digest checks engage.
cat > "$repo/Cargo.toml" <<'EOF'
[package]
name = "e2e"
version = "0.1.0"
edition = "2021"

[dependencies]
vulnerable = "0.1.0"
EOF
cat > "$repo/Cargo.lock" <<'EOF'
# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 3

[[package]]
name = "e2e"
version = "0.1.0"
dependencies = [
 "vulnerable",
]

[[package]]
name = "vulnerable"
version = "0.1.0"
EOF
cat > "$repo/go.mod" <<'EOF'
module example.com/e2e

go 1.22
EOF
cat > "$repo/main.go" <<'EOF'
package main

import "fmt"

func main() { fmt.Println("hello") }
EOF

# A synthetic offline OSV database in the pinned layout, with acquisition metadata
# the scanner verifies. Never production data.
build_db() {
  local dest="$1"
  shift
  python3 - "$dest" "$@" <<'PY'
import datetime, hashlib, json, os, sys, zipfile

dest = sys.argv[1]
mode = sys.argv[2] if len(sys.argv) > 2 else "valid"
now = datetime.datetime.now(datetime.timezone.utc)
for eco in ("Go", "crates.io"):
    d = os.path.join(dest, "osv-scalibr", eco)
    os.makedirs(d, exist_ok=True)
    path = os.path.join(d, "all.zip")
    pkg = "example.com/dep" if eco == "Go" else "dep"
    advisory = {
        "id": f"E2E-{eco}-0001",
        "modified": "2024-01-01T00:00:00Z",
        "published": "2024-01-01T00:00:00Z",
        "summary": "Controlled e2e advisory",
        "details": "Synthetic advisory for gate verification; no real vulnerability.",
        "affected": [{
            "package": {"name": pkg, "ecosystem": eco},
            "ranges": [{"type": "SEMVER", "events": [{"introduced": "0"}]}],
        }],
        "references": [{"type": "ADVISORY", "url": "https://example.com/e2e"}],
    }
    with zipfile.ZipFile(path, "w") as z:
        z.writestr("advisory.json", json.dumps(advisory))
    data = open(path, "rb").read()
    digest = hashlib.sha256(data).hexdigest()
    stamp = now
    if mode == "stale":
        stamp = now - datetime.timedelta(days=200)
    meta = {
        "downloaded_at": stamp.strftime("%Y-%m-%dT%H:%M:%SZ"),
        "ecosystem": eco,
        "sha256": digest,
        "size": len(data),
        "source": "synthetic-fixture",
    }
    if mode == "corrupt":
        meta["sha256"] = "0" * 64
    with open(path + ".metadata.json", "w") as fh:
        json.dump(meta, fh)
PY
}

build_db "$work/db-valid" valid
build_db "$work/db-stale" stale
build_db "$work/db-corrupt" corrupt
mkdir -p "$work/db-missing"

write_config() {
  local path="$1" db="$2" extra="${3:-}"
  cat > "$path" <<EOF
project:
  name: stage2-e2e
security:
  enabled: true
  mode: required
  scope: workspace
  required_categories: [sast, secrets, dependencies]
  fail_on: [critical, high]
  unknown_severity: indeterminate
  timeout_seconds: 180
  stale_advisory_database: deny
  osv_database_path: $db
  exclude: [.git]
  adapters:
    - id: gitleaks
      category: secrets
      protocol: builtin
      command: [gitleaks]
      version: "8.30.1"
    - id: semgrep
      category: sast
      protocol: builtin
      command: [semgrep]
      rules: $rules
      languages: [go]
      version: "1.183.0"
    - id: osv-scanner
      category: dependencies
      protocol: builtin
      command: [osv-scanner]
      languages: [go, rust]
      version: "2.7.0"
$extra
EOF
}

write_config "$work/cfg-valid.yaml" "$work/db-valid"
write_config "$work/cfg-missing.yaml" "$work/db-missing"
write_config "$work/cfg-stale.yaml" "$work/db-stale"
write_config "$work/cfg-corrupt.yaml" "$work/db-corrupt"
write_config "$work/cfg-unpinned.yaml" "$work/db-valid" "      binary_sha256_by_platform:
        linux/amd64: $(printf '0%.0s' $(seq 64))
        linux/arm64: $(printf '0%.0s' $(seq 64))
        darwin/amd64: $(printf '0%.0s' $(seq 64))
        darwin/arm64: $(printf '0%.0s' $(seq 64))"

failures=0
run_case() {
  local name="$1" want="$2" cfg="$3"
  local out
  out="$(cd "$repo" && "$sop_bin" security scan --config "$cfg" --json 2>/dev/null)" || true
  local got
  got="$(printf '%s' "$out" | python3 -c 'import json,sys; print(json.load(sys.stdin)["scan"]["verdict"])' 2>/dev/null || echo PARSE_ERROR)"
  if [ "$got" = "$want" ]; then
    printf 'stage2-gate-e2e: %-36s %s\n' "$name" "$got"
  else
    printf 'stage2-gate-e2e: %-36s FAIL got=%s want=%s\n' "$name" "$got" "$want" >&2
    printf '%s\n' "$out" | python3 -c 'import json,sys
d=json.load(sys.stdin)["scan"]
print("  reasons:", d.get("reasons"))
for a in d.get("adapters", []):
    diag=[x[:100] for x in (a.get("diagnostics") or [])][:2]
    print("  adapter", a["adapter_id"], a["status"], a["coverage"], diag)' >&2 || true
    failures=$((failures + 1))
  fi
}

run_case "valid database" PASS "$work/cfg-valid.yaml"
run_case "missing database" INDETERMINATE "$work/cfg-missing.yaml"
run_case "stale database" INDETERMINATE "$work/cfg-stale.yaml"
run_case "corrupt database" INDETERMINATE "$work/cfg-corrupt.yaml"
run_case "unpinned scanner binary" INDETERMINATE "$work/cfg-unpinned.yaml"

# Missing required language coverage: Rust content with no lockfile leaves the
# dependency category without complete coverage.
mv "$repo/Cargo.lock" "$work/Cargo.lock.bak"
run_case "missing required language coverage" INDETERMINATE "$work/cfg-valid.yaml"
mv "$work/Cargo.lock.bak" "$repo/Cargo.lock"

# A newly introduced unsuppressed HIGH finding must fail the gate.
cat > "$repo/bad.go" <<'EOF'
package main

import (
	"context"
	"os/exec"
)

func run(ctx context.Context, argv []string) error {
	return exec.CommandContext(ctx, argv[0], argv[1:]...).Run()
}
EOF
run_case "new unsuppressed HIGH finding" FAIL "$work/cfg-valid.yaml"
rm -f "$repo/bad.go"

if [ "$failures" -ne 0 ]; then
  echo "stage2-gate-e2e: FAILED ($failures case(s))" >&2
  exit 1
fi
echo "stage2-gate-e2e: OK (7 cases)"
